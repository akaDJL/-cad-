# ══════════════════════════════════════════════════════════
#  水力学公式
# ══════════════════════════════════════════════════════════

def manning_velocity(R: float, n: float, S: float) -> float:
    """曼宁公式计算流速 v (m/s)。
    R-水力半径(m), n-粗糙系数, S-水力坡度。
    v = (1/n) × R^(2/3) × S^(1/2)
    """
    if n <= 0 or R <= 0 or S <= 0:
        return 0.0
    return (1.0 / n) * (R ** (2.0 / 3.0)) * (S ** 0.5)


def manning_flow(A: float, R: float, n: float, S: float) -> float:
    """曼宁公式计算流量 Q (m³/s)。
    A-过水断面面积(m²)。
    """
    return A * manning_velocity(R, n, S)


def darcy_weisbach(v: float, L: float, D: float, f: float = 0.02,
                  g: float = 9.81) -> float:
    """达西-魏斯巴赫公式计算沿程水头损失 hf (m)。
    v-流速(m/s), L-管长(m), D-管径(m), f-沿程阻力系数。
    """
    if D <= 0:
        return 0.0
    return f * (L / D) * (v * v) / (2.0 * g)


def hazen_williams(Q: float, D: float, L: float, Ch: float = 120) -> float:
    """海曾-威廉公式计算给水管道水头损失 hf (m)。
    Q-流量(m³/s), D-管径(m), L-管长(m), Ch-海曾-威廉系数。
    """
    if D <= 0 or Ch <= 0:
        return 0.0
    return 10.67 * (Q ** 1.852) * L / ((Ch ** 1.852) * (D ** 4.8704))


def surface_load_area(Q: float, q: float) -> float:
    """表面负荷法计算沉淀池/滤池面积 A (m²)。
    Q-流量(m³/h), q-表面负荷(m³/m²·h)。
    """
    if q <= 0:
        return 0.0
    return Q / q


def retention_volume(Q: float, T: float) -> float:
    """停留时间法计算池容 V (m³)。
    Q-流量(m³/h), T-停留时间(h)。
    """
    return Q * T


# ══════════════════════════════════════════════════════════
#  大气治理公式
# ══════════════════════════════════════════════════════════

def baghouse_filter_area(Q: float, vf: float) -> float:
    """布袋除尘器过滤面积 A (m²)。
    Q-处理风量(m³/h), vf-过滤风速(m/min)。
    """
