def cable_voltage_drop(I: float, L: float, S: float,
                       cos_phi: float = 0.85,
                       material: str = "铜") -> float:
    """电缆电压损失 ΔU (%) 简化估算。
    I-电流(A), L-长度(m), S-截面(mm²), cos_phi-功率因数。
    """
    rho = 0.0184 if material == "铜" else 0.031
    R = rho * L / S
    Un = 380
    dU = 1.732 * I * R * cos_phi / (Un * 10) * 100
    return dU


def short_circuit_section(Ik: float, t: float, k: float = 171) -> float:
    """短路热稳定校验最小截面 S (mm²)。
    Ik-短路电流(kA), t-短路持续时间(s), k-热稳定系数(铜171, 铝92)。
    """
    return Ik * 1000 * (t ** 0.5) / k


def power_factor_correction(P_kW: float, cos1: float, cos2: float) -> float:
    """功率因数补偿所需电容容量 Qc (kvar)。
    P-有功功率(kW), cos1-补偿前, cos2-补偿后。
    """
    import math
    if cos1 >= 1.0 or cos2 >= 1.0:
        return 0.0
    tan1 = math.tan(math.acos(cos1))
    tan2 = math.tan(math.acos(cos2))
    return P_kW * (tan1 - tan2)


