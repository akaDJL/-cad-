def cooling_load(area: float, q: float) -> float:
    """面积指标法估算冷负荷 Q (W)。
    area-面积(m²), q-冷负荷指标(W/m²)。
    """
    return area * q


def supply_air_flow(Q: float, rho: float = 1.2, cp: float = 1.01,
                    delta_t: float = 8.0) -> float:
    """送风量 G (m³/h)。
    Q-全热负荷(kW), rho-空气密度(kg/m³), cp-比热(kJ/kg·K), delta_t-送风温差(℃)。
    """
    if delta_t <= 0:
        return 0.0
    return Q * 3600.0 / (rho * cp * delta_t)


def duct_velocity(Q: float, A: float) -> float:
    """风管内风速 v (m/s)。
    Q-风量(m³/h), A-截面积(m²)。
    """
    if A <= 0:
        return 0.0
    return Q / 3600.0 / A


def duct_pressure_loss(v: float, L: float, D_eq: float,
                       lambda_: float = 0.02) -> float:
    """风管沿程阻力 ΔP (Pa)。
    v-风速(m/s), L-长度(m), D_eq-当量直径(m)。
    """
    rho = 1.2
    if D_eq <= 0:
        return 0.0
    return lambda_ * (L / D_eq) * (rho * v * v) / 2.0


def water_pipe_flow(Q_kW: float, delta_t: float = 5.0,
                    cp: float = 4.1868) -> float:
    """空调水管流量 G (m³/h)。
    Q_kW-冷热负荷(kW), delta_t-供回水温差(℃)。
    """
    if delta_t <= 0:
        return 0.0
    return Q_kW * 3600.0 / (1000.0 * cp * delta_t)


