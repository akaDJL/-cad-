def substance_q(name: str) -> float:
    """取环境风险物质临界量 (t)。"""
    return RISK_SUBSTANCE_Q.get(name, 50)


def calc_emergency_pool_v(V1: float, V2_fire: float, V3: float = 0) -> float:
    """应急池容积 V = (V1+V2-V3)×安全系数。
    V1: 最大单罐/装置泄漏量 m³
    V2_fire: 消防废水量 m³
    V3: 可转输量 m³
    """
    raw = V1 + V2_fire - V3
    return max(raw, 0) * EMERGENCY_POOL["safety_factor"]


def stability_param(stab_class: str = "D") -> dict:
    return STABILITY.get(stab_class, STABILITY["D"])


def toxic_endpoint(substance: str) -> float:
    return TOXIC_ENDPOINT.get(substance, 100)


def emergency_code_list() -> list:
    return list(EMERGENCY_CODES.items())


def emergency_summary() -> str:
    return (f"风险物质阈值 {len(RISK_SUBSTANCE_Q)} 种 | 应急池参数 {len(EMERGENCY_POOL)} 项 | "
            f"稳定度 {len(STABILITY)} 级 | 毒性终点 {len(TOXIC_ENDPOINT)} 项 | "
            f"应急规范 {len(EMERGENCY_CODES)} 本")
