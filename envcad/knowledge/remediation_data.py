def soil_limit(pollutant: str, land_type: str = "I") -> float:
    """取建设用地土壤筛选值。land_type: I=第一类, II=第二类。"""
    entry = SOIL_SCREENING.get(pollutant)
    if entry:
        return entry.get(land_type, entry.get("I", 0))
    return 0


def gw_limit(pollutant: str) -> float:
    return GW_SCREENING.get(pollutant, 50)


def thermal_param(level: str = "低温热脱附") -> dict:
    return THERMAL_DESORPTION.get(level, THERMAL_DESORPTION["低温热脱附"])


def remediation_code_list() -> list:
    return list(REMEDIATION_CODES.items())


def remediation_summary() -> str:
    return (f"土壤筛选值 {len(SOIL_SCREENING)} 项 | 地下水 {len(GW_SCREENING)} 项 | "
            f"热脱附 {len(THERMAL_DESORPTION)} 级 | 修复规范 {len(REMEDIATION_CODES)} 本")
