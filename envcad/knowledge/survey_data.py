def gauss_zone(lon: float) -> tuple:
    """根据经度返回 6°带号与中央子午线。"""
    n = int((lon + 3) / 6) + (1 if (lon + 3) % 6 != 0 else 0)
    return n, 6 * n - 3


def gauss_zone_3(lon: float) -> tuple:
    """根据经度返回 3°带号与中央子午线。"""
    n = int((lon - 1.5) / 3) + 1
    return n, 3 * n


