def air_grade_judge(pmax: float, d10: float = 0) -> str:
    """根据 Pmax(%) 判定大气评价等级。"""
    if pmax >= 10 or (pmax >= 1 and d10 >= 5000):
        return "一级"
    if pmax >= 1:
        return "二级"
    return "三级"


def water_grade_judge(discharge_m3d: float, complexity: str = "简单") -> str:
    """根据日排水量(m³/d)与废水复杂程度判定地表水评价等级。"""
    if discharge_m3d >= 20000 or complexity == "复杂":
        return "一级"
    if discharge_m3d >= 2000 or complexity == "中等":
        return "二级"
    if discharge_m3d >= 200:
        return "三级A"
    return "三级B"


def noise_grade_judge(zone: str = "3类", delta: float = 2.0) -> str:
    """根据声功能区与增量 dB(A) 判定噪声评价等级。"""
    if zone in ("0类",) and delta >= 5:
        return "一级"
    if zone in ("0类", "1类", "2类") and delta >= 3:
        return "二级"
    if delta >= 5:
        return "一级"
    if delta >= 3:
        return "二级"
    return "三级"


def sensitive_area(name: str) -> dict:
    return SENSITIVE_AREA.get(name, dict(level="C", buffer=(50, 200)))


