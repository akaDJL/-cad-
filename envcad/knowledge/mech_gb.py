def angle_tolerance(grade, short_edge_mm):
    """返回冲压/弯曲角度公差(±度, 十进制)。grade 形如 'AT3' / 'BT4'。"""
    table = STAMPING_ANGLE_AT if grade.startswith("AT") else BENDING_ANGLE_BT
    if grade not in table:
        return None
    for i, bound in enumerate(ANGLE_L_BOUNDS):
        if short_edge_mm <= bound:
            return table[grade][i]
    return None


