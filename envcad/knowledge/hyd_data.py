# -*- coding: utf-8 -*-
"""液压行业知识库：液压油 + 标准缸径/杆径 + 压力等级 + 管路流速 + 规范。

把液压系统设计常用数据沉淀进插件，供液压缸、泵、管路计算与液压系统
设计计算书自动生成统一取数。数据为常用节选，具体以现行标准与产品
样本为准。

数据来源：
  - GB/T 2348  流体传动系统及元件 缸内径及活塞杆外径
  - GB/T 2346  流体传动系统及元件 公称压力系列
  - GB/T 786.1 流体传动系统及元件 图形符号
  - GB/T 7935  液压元件 通用技术条件
"""
from __future__ import annotations

import math

# ══════════════════════════════════════════════════════════
#  液压油牌号与运动黏度 (mm²/s, 40℃)
# ══════════════════════════════════════════════════════════
HYD_OIL = {
    "L-HM32": dict(visc=32,  rho=870, use="一般液压系统/低温"),
    "L-HM46": dict(visc=46,  rho=880, use="通用工业液压系统"),
    "L-HM68": dict(visc=68,  rho=880, use="高温/重载液压系统"),
    "L-HV46": dict(visc=46,  rho=875, use="低温/宽温液压系统"),
}

# ══════════════════════════════════════════════════════════
#  标准液压缸内径 (mm)  GB/T 2348
# ══════════════════════════════════════════════════════════
CYLINDER_BORE = [40, 50, 63, 80, 90, 100, 110, 125, 140, 160,
                 180, 200, 220, 250, 280, 320]
# 标准活塞杆直径 (mm)  GB/T 2348
PISTON_ROD = [18, 22, 25, 28, 32, 36, 40, 45, 50, 56, 63, 70,
              80, 90, 100, 110, 125, 140]

# ══════════════════════════════════════════════════════════
#  公称压力系列 (MPa)  GB/T 2346
# ══════════════════════════════════════════════════════════
PRESSURE_GRADE = [2.5, 6.3, 10, 16, 25, 31.5, 40, 63]

# ══════════════════════════════════════════════════════════
#  管路推荐流速 (m/s)  按管路类型
# ══════════════════════════════════════════════════════════
PIPE_VELOCITY = dict(
    吸油管=(0.5, 1.5),   # 泵吸油口
    压油管=(3.0, 6.0),   # 系统压力管
    回油管=(1.5, 2.5),   # 回油管
)
# 压力管流速随压力提高：p≤6.3 取5，p≤16 取6，p>16 取~7
PRESSURE_V = {6.3: 4.0, 16: 5.0, 25: 6.0, 31.5: 7.0}

# 标准无缝钢管外径×壁厚 (mm) 常用
STEEL_TUBE = {
    10: dict(od=14, wall=2), 15: dict(od=18, wall=2),
    20: dict(od=22, wall=2), 25: dict(od=28, wall=3),
    32: dict(od=34, wall=3), 40: dict(od=42, wall=3),
    50: dict(od=50, wall=4),
}

# ══════════════════════════════════════════════════════════
#  典型总效率
# ══════════════════════════════════════════════════════════
EFFICIENCY = dict(泵=0.85, 缸=0.95, 系统=0.75, 马达=0.90)

# ══════════════════════════════════════════════════════════
#  液压规范注册表
# ══════════════════════════════════════════════════════════
HYD_CODES = {
    "GB/T 2348-2018": "流体传动系统及元件 缸内径及活塞杆外径",
    "GB/T 2346-2003": "流体传动系统及元件 公称压力系列",
    "GB/T 786.1-2021": "流体传动系统及元件 图形符号",
    "GB/T 7935-2005": "液压元件 通用技术条件",
    "GB/T 3766-2015": "液压传动 系统及其元件的通用规则和安全要求",
    "JB/T 2184-2007": "液压元件 公称压力系列",
}


# ══════════════════════════════════════════════════════════
#  查询辅助
# ══════════════════════════════════════════════════════════
def oil(grade: str = "L-HM46") -> dict:
    return HYD_OIL.get(grade, HYD_OIL["L-HM46"])


def next_bore(d_req: float) -> float:
    for d in CYLINDER_BORE:
        if d >= d_req:
            return d
    return CYLINDER_BORE[-1]


def next_rod(d_req: float) -> float:
    for d in PISTON_ROD:
        if d >= d_req:
            return d
    return PISTON_ROD[-1]


def next_pressure(p_req: float) -> float:
    for p in PRESSURE_GRADE:
        if p >= p_req:
            return p
    return PRESSURE_GRADE[-1]


def pressure_velocity(p: float) -> float:
    for k in sorted(PRESSURE_V):
        if p <= k:
            return PRESSURE_V[k]
    return 7.0


def hyd_code_list() -> list:
    return list(HYD_CODES.items())


def hyd_summary() -> str:
    return (f"液压油 {len(HYD_OIL)} 种 | 标准缸径 {len(CYLINDER_BORE)} 档 | "
            f"活塞杆 {len(PISTON_ROD)} 档 | 压力等级 {len(PRESSURE_GRADE)} 档 | "
            f"液压规范 {len(HYD_CODES)} 本")
