def waterproof_sleeve(dn, kind="flexible", seal="I"):
    """查防水套管尺寸。kind='flexible'|'rigid'；seal='I'|'II'(仅柔性)。
    返回 dict 或 None。"""
    if kind == "flexible":
        row = FLEXIBLE_WATERPROOF_SLEEVE.get(dn)
        if not row:
            return None
        D1, D2, D3, D4, D5, l, l1, l2, d1, d2, b, nM, bolts, (wI, wII) = row
        w = wI if seal == "I" else wII
        return {"DN": dn, "D1": D1, "D2": D2, "D3": D3, "D4": D4, "D5": D5,
                "l": l, "l1": l1, "l2": l2, "d1": d1, "d2": d2, "b": b,
                "bolts": nM, "weight_kg": w}
    else:
        row = RIGID_WATERPROOF_SLEEVE_A.get(dn)
        if not row:
            return None
        D1, D2, D3, D4, delta, b, K, w = row
        return {"DN": dn, "D1": D1, "D2": D2, "D3": D3, "D4": D4,
                "delta": delta, "b": b, "K": K, "weight_kg": w}


