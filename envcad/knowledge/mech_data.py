def material_props(name: str) -> dict:
    return MECH_MATERIAL[name]


def round_to_module(m: float) -> float:
    """把计算模数向上圆整到标准模数（优先第一系列）。"""
    allm = sorted(MODULE_1)
    for v in allm:
        if v >= m:
            return v
    return allm[-1]


def round_to_std_diameter(d: float) -> int:
    """轴径向上圆整到标准直径。"""
    for v in STD_DIAMETER:
        if v >= d:
            return v
    return STD_DIAMETER[-1]


def thread_stress_area(spec: str) -> float:
    """螺纹应力截面积 As (mm2)。"""
    return THREAD_M[spec]["As"]


