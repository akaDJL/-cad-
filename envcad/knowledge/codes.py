def code_list() -> list:
    """返回 [(编号, 名称), ...] 供设计依据引用。"""
    return [(k, v["name"]) for k, v in GB_CODES.items()]


def code_names() -> str:
    """返回规范编号串，用于文档「设计依据」罗列。"""
    return "、".join(GB_CODES.keys())


def get_code(code: str) -> dict:
    return GB_CODES[code]


def load_factor(load: str = "可变荷载") -> float:
    """荷载分项系数快捷查询。"""
    return GB_CODES["GB 50009-2012"]["params"]["分项系数"][load]


def cover_min(member: str = "梁柱", env_class: str = "一类") -> int:
    """混凝土最小保护层厚度(mm)。"""
    return GB_CODES["GB 50010-2010(2015版)"]["params"]["混凝土保护层一类环境"][member]


def seismic_alpha_max(degree: float) -> float:
    """多遇地震水平影响系数最大值。degree 取 6/7/7.5/8/8.5/9。"""
    tbl = GB_CODES["GB 50011-2010(2016版)"]["params"]["设防烈度"]
    return tbl[degree]
