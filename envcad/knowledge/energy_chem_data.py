# ══════════════════════════════════════════════════════════
#  查询辅助
# ══════════════════════════════════════════════════════════
def vessel_material(name: str = "Q245R") -> dict:
    return VESSEL_MATERIAL.get(name, VESSEL_MATERIAL["Q245R"])


def weld_factor(method: str = "双面焊100%RT") -> float:
    return WELD_JOINT_FACTOR.get(method, 0.85)


def corrosion_allowance(level: str = "轻微腐蚀") -> float:
    return CORROSION_ALLOWANCE.get(level, 1.5)


def next_dp(dp: float) -> float:
    """向上取标准设计压力等级。"""
    for p in DESIGN_PRESSURE_LEVELS:
        if p >= dp:
            return p
    return DESIGN_PRESSURE_LEVELS[-1]


def exchanger_k(pair: str = "水-水(管壳式)") -> tuple:
    return K_EXCHANGER_DETAIL.get(pair, (500, 1500))


def packing_prop(packing_type: str = "DN38鲍尔环(金属)") -> dict:
    return PACKING_DATA.get(packing_type, PACKING_DATA["DN38鲍尔环(金属)"])


def next_tray_spacing(sp: float) -> int:
    for s in TRAY_SPACING:
        if s >= sp:
            return s
    return TRAY_SPACING[-1]


def pipe_support_spacing(dn: int) -> float:
    if dn in PIPE_SUPPORT_SPACING:
        return PIPE_SUPPORT_SPACING[dn]
    keys = sorted(PIPE_SUPPORT_SPACING)
    for k in keys:
        if k >= dn:
            return PIPE_SUPPORT_SPACING[k]
    return PIPE_SUPPORT_SPACING[keys[-1]]


def energy_chem_code_list() -> list:
    return list(ENERGY_CHEM_CODES.items())


