# ══════════════════════════════════════════════════════════
#  查询辅助
# ══════════════════════════════════════════════════════════
def water_quota(kind: str = "办公楼") -> dict:
    return WATER_QUOTA.get(kind, dict(q=50, unit="L/(人_d)", hours=10, Kh=1.5))


def fixture(kind: str = "洗脸盆水龙头") -> dict:
    return FIXTURE_UNIT.get(kind, dict(q0=0.20, Ng=1.0))


def pipe_di(dn: int) -> float:
    return PIPE_SPEC.get(dn, dict(di=dn))["di"]


def next_dn(dn_req: float) -> int:
    for dn in sorted(PIPE_SPEC):
        if dn >= dn_req:
            return dn
    return max(PIPE_SPEC)


def drain_slope(dn: int) -> tuple:
    return DRAIN_SLOPE.get(dn, (0.01, 0.004))


def plumb_code_list() -> list:
    return list(PLUMB_CODES.items())


def plumb_summary() -> str:
    return (f"用水定额 {len(WATER_QUOTA)} 类 | 给水器具 {len(FIXTURE_UNIT)} 种 | "
            f"管材 {len(PIPE_SPEC)} 档 | 排水坡度 {len(DRAIN_SLOPE)} 档 | "
            f"室外排水坡度 {len(SEWER_MIN_SLOPE)} 档 | 管材粗糙系数 {len(PIPE_ROUGHNESS_N)} 种 | "
            f"消防参数 {len(FIRE_WATER)} 项 | 排水立管 {len(DRAIN_STACK_CAPACITY)} 档 | "
            f"给排水规范 {len(PLUMB_CODES)} 本")
