# ══════════════════════════════════════════════════════════
#  查询辅助
# ══════════════════════════════════════════════════════════
def pipe_di(dn: int) -> float:
    return PIPE_SCHEDULE.get(dn, dict(di=dn))["di"]


def next_dn(dn_req: float) -> int:
    for dn in DN_SERIES:
        if dn >= dn_req:
            return dn
    return DN_SERIES[-1]


def econ_velocity(medium: str = "水_一般") -> tuple:
    return ECON_VELOCITY.get(medium, (1.0, 2.5))


def medium_prop(name: str = "水") -> dict:
    return MEDIUM.get(name, MEDIUM["水"])


def k_value(pair: str = "水-水") -> tuple:
    return K_HEAT_EXCHANGER.get(pair, (500, 1000))


def proc_code_list() -> list:
    return list(PROC_CODES.items())


def proc_summary() -> str:
    return (f"管道 {len(DN_SERIES)} 档(Sch40 {len(PIPE_SCHEDULE)}) | "
            f"经济流速 {len(ECON_VELOCITY)} 类 | 介质 {len(MEDIUM)} 种 | "
            f"换热K {len(K_HEAT_EXCHANGER)} 组 | 工艺规范 {len(PROC_CODES)} 本")
