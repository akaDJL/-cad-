def cable_ampacity(section: float, material: str = "铜") -> float:
    """取电缆载流量 (A)。material ∈ {铜, 铝}。"""
    idx = 0 if material == "铜" else 1
    if section in CABLE_AMPACITY:
        return CABLE_AMPACITY[section][idx]
    # 线性外插到最接近的档
    keys = sorted(CABLE_AMPACITY)
    for k in keys:
        if k >= section:
            return CABLE_AMPACITY[k][idx]
    return CABLE_AMPACITY[keys[-1]][idx]


def next_section(section: float) -> float:
    """向上取标准截面。"""
    for s in WIRE_SECTIONS:
        if s >= section:
            return s
    return WIRE_SECTIONS[-1]


def demand_factor(kind: str = "办公照明") -> dict:
    return DEMAND_FACTOR.get(kind, dict(Kx=0.5, cos=0.80))


def illuminance_std(place: str = "办公室") -> dict:
    return ILLUMINANCE_STD.get(place, dict(lx=300, ugr=19, ra=80))


def elec_code_list() -> list:
    return list(ELEC_CODES.items())


