def indoor_param(place: str = "办公室") -> dict:
    return DESIGN_INDOOR.get(place, DESIGN_INDOOR["办公室"])


def load_index(place: str = "办公室") -> dict:
    return LOAD_INDEX.get(place, dict(cool=110, heat=70))


def air_change(place: str = "办公室") -> float:
    return AIR_CHANGE.get(place, 3)


def next_duct(size_req: float) -> int:
    for w in DUCT_WIDTH:
        if w >= size_req:
            return w
    return DUCT_WIDTH[-1]


def hvac_code_list() -> list:
    return list(HVAC_CODES.items())


